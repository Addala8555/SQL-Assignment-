SELECT EMPLOYEE_ID,
FIRST_NAME,
DEPARTMENT_ID,
SALARY,
    CASE
        WHEN DEPARTMENT_ID = 60
         AND SALARY >=1000
          THEN 'SENIOR IT EMPLOPYEE'
        WHEN DEPARTMENT_ID = 60
         AND SALARY < 1000
          THEN 'JUNIOR IT EMPLOPYEE'
        WHEN DEPARTMENT_ID = 80
         AND SALARY>=1000
          THEN 'SENIOR SALES EMPLOYEE'
        WHEN DEPARTMENT_ID = 80
         AND SALARY < 1000
         THEN 'JUNIOR SALES EMPLOYEE'
    ELSE 'OTHER EMPLOYEE'
END AS EMPLOYEE_STATUS
FROM HR.EMPLOYEES